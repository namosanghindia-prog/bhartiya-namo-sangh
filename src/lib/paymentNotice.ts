/** Bumping this re-shows the notice to everyone, even past visitors. */
export const NOTICE_STORAGE_KEY = "bns-payment-notice-v1";
export const NOTICE_LANG_KEY = "bns-payment-notice-lang";

export const DEFAULT_LOCALE = "hi";

/** Picks the best locale for the visitor's browser, falling back to Hindi. */
export function pickLocale(navigatorLanguages: readonly string[]): NoticeLocale {
  for (const tag of navigatorLanguages) {
    const base = tag.toLowerCase().split("-")[0];
    const hit = NOTICE_LOCALES.find((l) => l.code === base);
    if (hit) return hit;
  }
  return NOTICE_LOCALES.find((l) => l.code === DEFAULT_LOCALE) ?? NOTICE_LOCALES[0];
}
